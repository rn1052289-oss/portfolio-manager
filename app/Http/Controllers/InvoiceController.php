     */
    /**
     * ログインユーザーの請求書一覧を表示します。
     */
    public function index()
    {
        $this->authorize('viewAny', Invoice::class);

        $invoices = Invoice::query()
            ->where('user_id', auth()->id())
            ->with([
                'project:id,title',
                'customer:id,name',
            ])
            ->latest('id')
            ->paginate(10);

        return view('invoices.index', [
            'invoices' => $invoices,
        ]);
    }

